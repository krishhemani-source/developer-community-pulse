// "/history/[week]" One past brief, read-only.
import Link from "next/link";
import { notFound } from "next/navigation";
import { BriefView } from "@/components/brief-view";
import { LoadError } from "@/components/states";
import { getBriefByWeek, load } from "@/lib/queries";
import { formatWeekRange } from "@/lib/weeks";

export const dynamic = "force-dynamic";

export default async function PastBriefPage({ params }: { params: Promise<{ week: string }> }) {
  const { week } = await params;
  const result = await load(() => getBriefByWeek(week));
  if (!result.ok) return <LoadError result={result} />;
  if (!result.data) notFound();
  const b = result.data.content;

  return (
    <div className="flex flex-col gap-10">
      <header className="border-b border-rule pb-6">
        <Link href="/history" className="text-sm text-muted hover:text-ink">
          All past briefs
        </Link>
        <p className="tabular mt-2 text-2xl font-semibold tracking-tight">{formatWeekRange(b.weekStart, b.weekEnd)}</p>
        <p className="text-sm text-muted">Read-only. Generated by a {b.trigger} run · email {result.data.email_status}</p>
      </header>
      <BriefView brief={b} markdown={result.data.summary_markdown} />
    </div>
  );
}
